"""Step 4: feasibility check for RQ2 -- does exogenous (random) exposure feed back into
later algorithmic exposure?

Design A (platform level): video x day panel, 2022-04-22..05-08. Regress next-day algorithmic
  impressions on today's random impressions with video and day fixed effects. Random impressions
  are assigned by the platform's random replacement, so given the fixed effects their day-to-day
  variation is noise. Placebo: today's random impressions should not predict yesterday's.
Design B (user level): treated = (user u, time t, author a) where u was randomly shown a video by a.
  Control = same user, same time, a uniformly drawn pool video that u had not seen before t (in any
  log, including the earlier standard log), by an author u was never randomly shown. A first version
  without the "not seen before t" condition failed the placebo: the random slot avoids videos the user
  has already seen (de-duplication, measured in section B0), and the algorithm never re-shows a watched
  video. So the outcome is restricted to the creator's OTHER videos (creators with >= 2 pool videos):
  u gets an algorithmic impression of another video by a in (t, t+7d]. Placebo: same outcome in [t-7d, t).

Output: reports/04_feasibility.md. Every number in the report is computed below.
"""
from pathlib import Path
import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
P = ROOT / "data/processed"
DAY_MS = 86_400_000                      # one day in milliseconds
out = ["# Feasibility: random exposure shocks (generated by src/04_feasibility_random_shock.py)\n"]
def log(s=""):
    """Print a line and keep it for the report file."""
    print(s)
    out.append(s)

def cluster_se(d, groups):
    """Standard error of the mean of d, clustered by groups.
    Sum the deviations (d_i - mean) within each cluster first, then square: observations from the same
    user are allowed to be correlated. SE = sqrt(sum_g (sum_{i in g} (d_i - mean))^2) / N."""
    d = np.asarray(d, float)
    s = pd.Series(d - d.mean()).groupby(np.asarray(groups)).sum()
    return np.sqrt((s**2).sum()) / len(d)

# all three logs: used only to know which videos each user had already been shown, and when
allv = pd.read_parquet(P / "interactions.parquet", columns=["source", "user_id", "video_id", "time_ms"])
inter = pd.read_parquet(P / "interactions.parquet",
                        columns=["source", "user_id", "video_id", "author_id", "time_ms", "event_time",
                                 "long_view", "is_like", "is_follow", "is_ad"])
# the analysis uses the random log and the standard log of the SAME period, without ads
inter = inter[inter.source.isin(["random", "std_main"]) & ~inter.is_ad]
rnd = inter[inter.source == "random"]
std = inter[inter.source == "std_main"]
pool = pd.read_parquet(P / "videos.parquet", columns=["video_id", "author_id", "is_ad"]).query("~is_ad")

# ---------------- Design A: video-day panel ----------------
log("## A. Platform level: video x day panel")
days = pd.date_range("2022-04-22", "2022-05-08").date
grid = pd.MultiIndex.from_product([pool.video_id, days], names=["video_id", "day"])   # every video x every day
cnt = lambda d: d.groupby([d.video_id, d.event_time.dt.date.rename("day")]).size()   # impressions per video-day
panel = pd.DataFrame({"R": cnt(rnd).reindex(grid, fill_value=0),        # random impressions
                      "A": cnt(std).reindex(grid, fill_value=0),        # algorithmic impressions
                      "LV": rnd.groupby([rnd.video_id, rnd.event_time.dt.date.rename("day")])
                               .long_view.sum().reindex(grid, fill_value=0)}).reset_index()   # random long views
panel = panel.sort_values(["video_id", "day"])
g = panel.groupby("video_id")
panel["A_next"], panel["A_prev"] = g.A.shift(-1), g.A.shift(1)          # tomorrow's / yesterday's algorithmic impressions

def twfe(df, y, xs):
    """Two-way fixed effects (video + day) via iterative demeaning; OLS with video-clustered SE.
    Repeatedly subtracting video means and day means leaves only variation within a video over time that is
    not common to all videos on that day; OLS on what remains = the fixed-effects estimate.
    Clustered SE: scores X_i * e_i are summed within each video before forming the variance."""
    df = df.dropna(subset=[y] + xs).copy()
    cols = [y] + xs
    for _ in range(20):
        for k in ("video_id", "day"):
            df[cols] = df[cols] - df.groupby(k)[cols].transform("mean")
    X, Y = df[xs].values, df[y].values
    bread = np.linalg.inv(X.T @ X)
    b = bread @ X.T @ Y
    e = Y - X @ b
    sc = pd.DataFrame(X * e[:, None]).groupby(df.video_id.values).sum().values
    se = np.sqrt(np.diag(bread @ sc.T @ sc @ bread))
    return b, se

m = panel.R.mean()
# var/mean: about 1 if per-video-day random counts were Poisson-like draws with a constant rate
log(f"- {panel.video_id.nunique():,} videos x {len(days)} days; random impressions per video-day: "
    f"mean {m:.2f}, var/mean {panel.R.var() / m:.2f} (Poisson-like noise = 1); "
    f"algorithmic impressions per video-day: mean {panel.A.mean():.2f}")
daily_r = rnd.groupby(rnd.event_time.dt.date).size()                    # total random impressions per day
log(f"- total random impressions per day: min {daily_r.min():,}, max {daily_r.max():,} "
    f"(max/min {daily_r.max() / daily_r.min():.1f})")
rows, est = [], {}
for label, y, xs in [("A(d+1) ~ R(d)", "A_next", ["R"]),
                     ("A(d+1) ~ R(d) + random long views(d)", "A_next", ["R", "LV"]),
                     ("Placebo: A(d-1) ~ R(d)", "A_prev", ["R"])]:
    b, se = twfe(panel, y, xs)
    est[label] = (b[0], se[0])                           # coefficient and SE of R
    rows.append({"Model": label, **{x: f"{bi:.4f} ({si:.4f})" for x, bi, si in zip(xs, b, se)}})
log("\nVideo and day fixed effects, SE clustered by video:\n")
log(pd.DataFrame(rows).fillna("").to_markdown(index=False) + "\n")
(b_main, _), (b_pl, se_pl) = est["A(d+1) ~ R(d)"], est["Placebo: A(d-1) ~ R(d)"]
verdict = "fails" if abs(b_pl / se_pl) > 1.96 else "passes"     # placebo should be ~0 if the design is clean
log(f"**Placebo {verdict}**: placebo coefficient {b_pl:.4f}, z = {b_pl / se_pl:.1f} "
    f"(main effect {b_main:.4f}). Today's random impressions 'predict' yesterday's algorithmic impressions "
    f"about as strongly as tomorrow's, and random impressions are over-dispersed. Daily random traffic varies by the factor shown "
    "above, and if it scales multiplicatively with video-level rates, additive fixed effects do not absorb it "
    "(a likely explanation, not tested here). Not usable as is; the point estimate (~0.01 algorithmic impressions "
    "per random impression) suggests any effect is tiny.\n")

# ---------------- B0: does the random slot avoid videos the user has already seen? ----------------
log("## B0. De-duplication of the random slot")
# first time each user was shown each video, in any of the three logs
first = allv.groupby(["user_id", "video_id"]).time_ms.min().rename("t_first").reset_index()
r_all = allv[allv.source == "random"][["user_id", "video_id", "time_ms"]]
r_all = r_all.merge(first, on=["user_id", "video_id"])
seen_share = (r_all.t_first < r_all.time_ms).mean()     # random impression of a video already shown to that user
# chance benchmark: if the slot ignored history and drew uniformly from the pool, the chance of hitting an
# already-seen video = (distinct pool videos the user had been shown before t) / pool size
first = first.sort_values(["user_id", "t_first"])
first["k_seen"] = first.groupby("user_id").cumcount() + 1   # number of distinct videos shown up to and incl. this one
r_sorted = r_all.sort_values("time_ms")
k_prior = pd.merge_asof(r_sorted, first.sort_values("t_first")[["user_id", "t_first", "k_seen"]],
                        left_on="time_ms", right_on="t_first", by="user_id",
                        direction="backward", allow_exact_matches=False).k_seen.fillna(0)
n_pool = pd.read_parquet(P / "videos.parquet", columns=["video_id"]).shape[0]
expected = (k_prior / n_pool).mean()
log(f"- random impressions showing a video the user had already been shown (any log, earlier time): "
    f"{seen_share:.3%}; expected if the slot ignored viewing history: {expected:.3%} "
    f"(ratio {seen_share / expected:.2f})\n")

# ---------------- Design B: user-level randomized comparison ----------------
log("## B. User level: does a random exposure to a creator lead the algorithm to show the same user "
    "another video by that creator?")
nvid = pool.author_id.value_counts()
multi = nvid[nvid >= 2].index                        # creators with >= 2 pool videos ("another video" must exist)
treat = (rnd.sort_values("time_ms").drop_duplicates(["user_id", "author_id"])   # first random exposure per user-author
         .query("author_id in @multi")[["user_id", "author_id", "video_id", "time_ms",
                                        "long_view", "is_like", "is_follow"]])
rng = np.random.default_rng(42)                      # fixed seed: the control draw is reproducible
ctrl = treat[["user_id", "time_ms"]].copy()          # same user, same time as each treated pair
draw = pool[pool.author_id.isin(multi)].sample(len(ctrl), replace=True, random_state=rng)
ctrl["video_id"], ctrl["author_id"] = draw.video_id.values, draw.author_id.values
# drop controls whose author the user was ever randomly shown (they would be "treated" for that author)
ever = rnd[["user_id", "author_id"]].drop_duplicates().assign(_seen=True)
ctrl = ctrl.merge(ever, on=["user_id", "author_id"], how="left")
ctrl = ctrl[ctrl._seen.isna()].drop(columns="_seen").reset_index(drop=True)
# drop controls whose video the user had already been shown before t (any log): treated videos are never
# such videos because of the de-duplication measured in B0
seen = allv[["user_id", "video_id", "time_ms"]].rename(columns={"time_ms": "t_seen"})
prev = ctrl.reset_index().merge(seen, on=["user_id", "video_id"])
ctrl = ctrl.drop(index=prev[prev.t_seen < prev.time_ms]["index"].unique())

# algorithmic impressions by user and author (the outcome looks for the author's OTHER videos)
std_ua = std[["user_id", "author_id", "video_id", "time_ms"]].rename(
    columns={"video_id": "video_s", "time_ms": "time_s"})

def add_outcomes(df):
    """post = the algorithm showed u another video by a within 7 days after t;
    pre (placebo) = the same within 7 days before t. Windows are cut at the edges of the std_main
    period (22 Apr - 8 May) in the same way for treated and control pairs."""
    df = df.reset_index(drop=True)
    df["rid"] = df.index
    mm = df[["rid", "user_id", "author_id", "video_id", "time_ms"]].merge(std_ua, on=["user_id", "author_id"])
    mm = mm[mm.video_s != mm.video_id]                       # only the creator's OTHER videos
    dt = (mm.time_s - mm.time_ms) / DAY_MS                   # days between t and the algorithmic impression
    df["post"] = df.rid.isin(mm[(dt > 0) & (dt <= 7)].rid)
    df["pre"] = df.rid.isin(mm[(dt < 0) & (dt >= -7)].rid)
    return df

treat, ctrl = add_outcomes(treat), add_outcomes(ctrl)
log(f"- treated user-creator pairs: {len(treat):,}; control pairs: {len(ctrl):,} (same users, same times)\n")
rows, zstat = [], {}
for y, note in [("pre", "placebo: 7 days before"), ("post", "7 days after")]:
    pt, pc = treat[y].mean(), ctrl[y].mean()
    # SE of a difference between two independent group means, each clustered by user
    se = np.sqrt(cluster_se(treat[y], treat.user_id)**2 + cluster_se(ctrl[y], ctrl.user_id)**2)
    rows.append({"Window": note, "Treated": f"{pt:.4%} ({int(treat[y].sum())} events)",
                 "Control": f"{pc:.4%} ({int(ctrl[y].sum())} events)",
                 "Diff (pp)": f"{100 * (pt - pc):.4f}", "SE (pp)": f"{100 * se:.4f}",
                 "Diff / SE": f"{(pt - pc) / se:.2f}"})
    zstat[y] = (pt - pc) / se
    if y == "post":
        # minimum detectable effect relative to the control rate: (1.96 + 0.84) * SE / control mean
        mde = 2.8 * se / pc
log(pd.DataFrame(rows).to_markdown(index=False) + "\n")
log(f"- Placebo {'passes' if abs(zstat['pre']) < 1.96 else 'fails'} (|z| = {abs(zstat['pre']):.2f}); "
    f"post effect {'not ' if abs(zstat['post']) < 1.96 else ''}significant (z = {zstat['post']:.2f}). "
    f"Minimum detectable relative effect (80% power, 5% level) ≈ {mde:.0%}.\n")

log("Descriptive (not randomized): treated pairs split by the user's response to the random exposure. "
    "The response is chosen by the user, so these are not causal; groups with few events are not interpretable.\n")
rows = []
for lab, mask in [("no long view", treat.long_view == 0), ("long view", treat.long_view == 1),
                  ("like", treat.is_like == 1), ("follow", treat.is_follow == 1)]:
    rows.append({"Response": lab, "n": int(mask.sum()), "events": int(treat.loc[mask, "post"].sum()),
                 "P(post)": f"{treat.loc[mask, 'post'].mean():.3%}"})
log(pd.DataFrame(rows).to_markdown(index=False) + "\n")

(ROOT / "reports/04_feasibility.md").write_text("\n".join(out) + "\n")
