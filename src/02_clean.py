"""Step 2: clean KuaiRand-Pure.

Reads data/raw (never modified), writes data/processed/*.parquet and reports/02_cleaning_log.md.
Principle: only drop rows that are certain logging artefacts; flag everything else.

Outputs
  interactions.parquet : the three logs stacked (one row = one impression of one video to one user)
  videos.parquet       : one row per pool video (basic features + monthly statistics)
  users.parquet        : one row per user
Every number written to the cleaning log is computed below; nothing is typed in by hand.
"""
from pathlib import Path
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / "data/raw/KuaiRand-Pure/data"
OUT = ROOT / "data/processed"
LOG = ROOT / "reports/02_cleaning_log.md"
OUT.mkdir(exist_ok=True)

report = ["# Cleaning log (generated by src/02_clean.py)\n"]
def log(s=""):
    """Print a line and keep it for the cleaning log (the terminal output IS the log)."""
    print(s)
    report.append(s)

LOG_FILES = {
    "random": "log_random_4_22_to_5_08_pure.csv",      # randomly exposed videos, 04-22..05-08
    "std_main": "log_standard_4_22_to_5_08_pure.csv",  # standard recommender, same period
    "std_pre": "log_standard_4_08_to_4_21_pure.csv",   # standard recommender, previous two weeks
}
# 0/1 columns in the logs; checked below so that no other code value slips through
BINARY = ["is_click", "is_like", "is_follow", "is_comment", "is_forward", "is_hate",
          "long_view", "is_profile_enter", "is_rand"]
# event key: the same user, the same video, the same millisecond = the same impression
KEY = ["user_id", "video_id", "time_ms"]

# ---------- videos ----------
vb = pd.read_csv(RAW / "video_features_basic_pure.csv")       # author, type, duration, upload date ...
vs = pd.read_csv(RAW / "video_features_statistic_pure.csv")   # platform-wide monthly statistics
# both tables must have exactly one row per video and contain the same videos, otherwise the merge is unsafe
assert vb.video_id.is_unique and vs.video_id.is_unique and set(vb.video_id) == set(vs.video_id)
for c in ["video_type", "upload_type"]:
    vb[c] = vb[c].replace("UNKNOWN", pd.NA)                   # placeholder text -> real missing value
vb["upload_dt"] = pd.to_datetime(vb.upload_dt)                # text date -> datetime
vb["is_ad"] = vb.video_type.eq("AD").fillna(False)            # flag ads (kept, excluded later in 03)
videos = vb.merge(vs, on="video_id", how="inner", validate="1:1")   # validate: fail if not one-to-one
log("## videos")
log(f"- {len(videos)} videos, {videos.author_id.nunique()} authors; ads flagged: {int(videos.is_ad.sum())}; "
    f"video_type unknown -> NA: {int(vb.video_type.isna().sum())}")
log(f"- video_duration missing: {int(videos.video_duration.isna().sum())} (left as NA; logs have no duration for them either). "
    f"By upload_type: {videos[videos.video_duration.isna()].upload_type.value_counts().to_dict()} -> mostly picture posts")
log(f"- constant columns kept as-is: {[c for c in videos.columns if videos[c].nunique(dropna=False) == 1]}")
log("- statistic columns are daily averages over one month (see dataset docs), not totals\n")

# ---------- users ----------
users = pd.read_csv(RAW / "user_features_pure.csv")
assert users.user_id.is_unique
# -124 is the dataset's code for "unknown"; left as a number it would distort means (profile mean = -95.8)
n_live = int((users.is_live_streamer == -124).sum())
users["is_live_streamer"] = users.is_live_streamer.replace(-124, pd.NA).astype("Int64")   # Int64 = integer that can hold NA
users["user_active_degree"] = users.user_active_degree.replace("UNKNOWN", pd.NA)
for c in users.columns:
    if c.startswith("onehot_feat") and users[c].isna().any():
        users[c] = users[c].astype("Int64")                   # keep the NA, only change the dtype
log("## users")
log(f"- {len(users)} users; is_live_streamer == -124 (missing code) -> NA: {n_live}")
log(f"- onehot_feat NA kept as NA: {users.filter(like='onehot').isna().sum()[lambda s: s > 0].to_dict()}\n")

# ---------- interactions ----------
log("## interactions")
parts = []
for src, fname in LOG_FILES.items():
    d = pd.read_csv(RAW / fname)
    n0 = len(d)
    # sanity checks: 0/1 columns really are 0/1, and is_rand matches the file it came from
    assert d[BINARY].isin([0, 1]).all().all(), f"{src}: non-binary value in binary column"
    assert (d.is_rand == (1 if src == "random" else 0)).all(), f"{src}: is_rand inconsistent with file"
    # Same (user, video, millisecond timestamp) = the same event logged twice (rows differ almost
    # only in the hourly bucket date/hourmin). Keep one: the row with the longest play time.
    # Sort by key, and within a key by play_time_ms descending, so keep="first" keeps the longest play.
    d = d.sort_values(KEY + ["play_time_ms"], ascending=[True, True, True, False])
    d = d.drop_duplicates(KEY, keep="first")
    log(f"- {src}: raw {n0:,} rows -> {len(d):,} after removing {n0 - len(d):,} duplicate events "
        f"({(n0 - len(d)) / n0:.2%})")
    d.insert(0, "source", src)                                # which log the row came from
    parts.append(d)
inter = pd.concat(parts, ignore_index=True)                   # stack the three logs into one table

# every logged video / user must exist in the feature tables (Pure logs contain only pool videos)
assert inter.video_id.isin(videos.video_id).all() and inter.user_id.isin(users.user_id).all()

# time_ms is the canonical event time; date/hourmin are the logging hour (0-1h later) and kept raw.
inter["event_time"] = pd.to_datetime(inter.time_ms, unit="ms", utc=True).dt.tz_convert("Asia/Shanghai")

# duration_ms == 0 in some log rows: fill from video metadata, flag it.
# m:1 = many log rows per video; validate makes the merge fail if a video appeared twice in `videos`
inter = inter.merge(videos[["video_id", "author_id", "video_duration", "is_ad"]], on="video_id",
                    how="left", validate="m:1")
inter["duration_imputed"] = inter.duration_ms.eq(0) & inter.video_duration.notna()     # True = filled in
inter["duration_ms_clean"] = inter.duration_ms.where(inter.duration_ms > 0, inter.video_duration)
inter["play_ratio"] = inter.play_time_ms / inter.duration_ms_clean    # > 1 means the user replayed it
inter = inter.drop(columns="video_duration")
log(f"- duration_ms == 0 filled from video metadata: {int(inter.duration_imputed.sum()):,}; "
    f"still missing: {int(inter.duration_ms_clean.isna().sum()):,} (all on the no-duration videos above; play_ratio = NA)")
# denominator = all rows, including the rows whose play_ratio is NA
log(f"- play_ratio > 1 (replays) kept: {(inter.play_ratio > 1).mean():.1%} of rows")
log(f"- final: {len(inter):,} rows | by source: {inter.source.value_counts().to_dict()}")
log(f"- rows on ad videos (flag is_ad, not removed): {int(inter.is_ad.sum()):,}\n")

# ---------- write ----------
inter.to_parquet(OUT / "interactions.parquet", index=False)
videos.to_parquet(OUT / "videos.parquet", index=False)
users.to_parquet(OUT / "users.parquet", index=False)
log("## outputs")
for f in sorted(OUT.glob("*.parquet")):
    log(f"- data/processed/{f.name} ({f.stat().st_size / 1e6:.1f} MB)")
LOG.write_text("\n".join(report) + "\n")
