"""Step 3: preliminary analysis for the proposal.

Quality   q_i : how good video i is when shown to RANDOM users (random log -> no selection bias).
                Empirical-Bayes-shrunk long_view rate; also a duration-adjusted percentile, because
                long_view is mechanically easier for short videos.
Exposure  E_i : how often the standard recommender showed video i to the same users in the same
                period (std_main log). Prior exposure E_pre from the previous two weeks (std_pre).

Outputs: reports/03_prelim_results.md, reports/figures/*.png, data/processed/video_level.parquet
Every number in the report is computed in this script (no hand-typed results).
"""
from pathlib import Path
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from scipy.stats import spearmanr

ROOT = Path(__file__).resolve().parents[1]
P = ROOT / "data/processed"
FIG = ROOT / "reports/figures"
FIG.mkdir(parents=True, exist_ok=True)
MIN_RANDOM_IMPS = 50          # a video needs >= 50 random impressions for a usable quality estimate
BLUE, ORANGE, GRAY, INK, INK2 = "#2a78d6", "#eb6834", "#b4b2ab", "#0b0b0b", "#52514e"
plt.rcParams.update({"font.size": 10, "axes.edgecolor": GRAY, "axes.labelcolor": INK2,
                     "xtick.color": INK2, "ytick.color": INK2, "axes.spines.top": False,
                     "axes.spines.right": False, "figure.dpi": 150, "savefig.bbox": "tight"})

out = ["# Preliminary results (generated by src/03_prelim_analysis.py)\n"]
def log(s=""):
    """Print a line and keep it for the report file."""
    print(s)
    out.append(s)

def gini(x):
    """Gini coefficient of a non-negative array: 0 = everyone gets the same, -> 1 = one item gets everything.
    With x sorted ascending and ranks i = 1..n:  G = sum_i (2i - n - 1) x_i / (n * sum_i x_i).
    Example: [25, 25, 25, 25] -> 0;  [0, 0, 0, 100] -> 0.75."""
    x = np.sort(np.asarray(x, float))
    n = len(x)
    return (2 * np.arange(1, n + 1) - n - 1) @ x / (n * x.sum())

def lorenz(x):
    """Points of the Lorenz curve: x = cumulative share of items (least exposed first),
    y = cumulative share of the total they receive. Equality = the 45-degree line."""
    x = np.sort(np.asarray(x, float))
    return np.r_[0, np.arange(1, len(x) + 1) / len(x)], np.r_[0, x.cumsum() / x.sum()]

def eb_shrink(k, n):
    """Beta-binomial empirical Bayes (method of moments).
    k = long views, n = impressions per video. Raw rate r = k/n is noisy when n is small.
    1. prior mean m = average raw rate over videos;
    2. true between-video variance = observed variance of r minus average binomial noise m(1-m)/n;
    3. prior strength alpha + beta = m(1-m)/var_true - 1 (a Beta prior with mean m and that variance);
    4. posterior mean (k + alpha) / (n + alpha + beta), with alpha = m * (alpha + beta).
    Videos with few impressions are pulled more towards m; videos with many keep their own rate."""
    r = k / n
    m = r.mean()
    var_true = max(r.var() - (m * (1 - m) / n).mean(), 1e-8)   # floor avoids division by ~0
    ab = m * (1 - m) / var_true - 1                             # alpha + beta
    return (k + m * ab) / (n + ab)

def ols_hc1(y, X):
    """OLS with a constant and HC1 heteroskedasticity-robust standard errors.
    Returns (coefficients, standard errors, R^2), constant excluded from the first two.
    HC1: V = (X'X)^-1 X' diag(e^2) X (X'X)^-1 * n / (n - k)  -- it changes only the s.e., not b."""
    X = np.column_stack([np.ones(len(X)), X])          # add the constant
    b = np.linalg.lstsq(X, y, rcond=None)[0]           # least-squares coefficients
    e = y - X @ b                                      # residuals
    bread = np.linalg.inv(X.T @ X)
    V = bread @ (X.T * e**2) @ X @ bread * len(y) / (len(y) - X.shape[1])
    r2 = 1 - e @ e / ((y - y.mean()) @ (y - y.mean()))
    return b[1:], np.sqrt(np.diag(V))[1:], r2

# ---------- build video-level table ----------
inter = pd.read_parquet(P / "interactions.parquet")
videos = pd.read_parquet(P / "videos.parquet").set_index("video_id")

# random log -> per video: number of random impressions, long views, likes
rnd = inter[inter.source == "random"].groupby("video_id").agg(
    n_rand=("long_view", "size"), lv_k=("long_view", "sum"), like_k=("is_like", "sum"))
V = videos[["author_id", "video_duration", "is_ad", "upload_type"]].join(rnd)
# standard logs -> per video: current exposure E (std_main) and prior exposure E_pre (std_pre); 0 if never shown
for s, col in [("std_main", "E"), ("std_pre", "E_pre")]:
    V[col] = inter[inter.source == s].video_id.value_counts().reindex(V.index, fill_value=0)
# long-view rate in the algorithm's own feed (only used to check that random-log quality carries over)
sm = inter[inter.source == "std_main"].groupby("video_id").long_view.agg(["sum", "size"])
V["lv_std"] = sm["sum"] / sm["size"]
V["n_std"] = sm["size"]

n_all = len(V)
n_std_cov = inter[inter.source != "random"].video_id.nunique()     # pool videos that appear in either standard log
V = V[~V.is_ad & V.video_duration.notna() & (V.n_rand >= MIN_RANDOM_IMPS)].copy()
log("## Sample")
log(f"- pool: {n_all:,} videos, all in the random log; {n_std_cov:,} of them appear in at least one standard log")
log(f"- {len(V):,} of {n_all:,} videos kept (drop ads, posts without a video duration, "
    f"< {MIN_RANDOM_IMPS} random impressions); {V.author_id.nunique():,} creators")
log(f"- random impressions per video: median {V.n_rand.median():.0f}; "
    f"algorithmic impressions (same users, same period): median {V.E.median():.0f}, "
    f"zero for {(V.E == 0).mean():.1%} of videos\n")

V["q"] = eb_shrink(V.lv_k, V.n_rand)                                 # shrunk long-view rate
V["dur_decile"] = pd.qcut(V.video_duration, 10, labels=False)       # 10 equal-size duration groups
V["q_adj"] = V.groupby("dur_decile").q.rank(pct=True)          # main quality measure: percentile within duration group
V["E_pct"] = V.E.rank(pct=True, method="average")                   # exposure percentile (for the scatter plot)

# reliability: split random log by user_id parity, re-estimate quality in each half
# If q_adj measures a stable property of the video, two disjoint sets of users should rank videos alike.
r_in = inter[(inter.source == "random") & inter.video_id.isin(V.index)]
half = {}
for h in (0, 1):
    k = r_in[r_in.user_id % 2 == h].groupby("video_id").long_view.agg(["sum", "size"]).reindex(V.index)
    half[h] = eb_shrink(k["sum"], k["size"]).groupby(V.dur_decile).rank(pct=True)
rho_half = spearmanr(half[0], half[1]).statistic
log("## Quality measure reliability")
# Spearman-Brown 2r/(1+r): each half has half the data, so r understates the full-sample reliability
log(f"- split-half Spearman {rho_half:.3f}; Spearman-Brown full-sample reliability {2 * rho_half / (1 + rho_half):.3f}")
log(f"- top-quartile videos in half A that are also top-quartile in half B: "
    f"{(half[1][half[0] >= 0.75] >= 0.75).mean():.1%} (chance 25%)\n")

# ---------- R1 concentration ----------
log("## R1. Exposure concentration")
# creator-level table (only the creator's videos in the analysis sample are counted)
A = V.groupby("author_id").agg(E=("E", "sum"), n_rand=("n_rand", "sum"), E_pre=("E_pre", "sum"),
                               q_sum=("q_adj", "sum"), n_videos=("q", "size"))
rows = []
for name, vid, auth in [("Random exposure", V.n_rand, A.n_rand), ("Algorithmic exposure", V.E, A.E)]:
    s = np.sort(vid.values)[::-1]                      # most exposed first
    rows.append([name, gini(vid), s[: len(s) // 100].sum() / s.sum(), s[: len(s) // 10].sum() / s.sum(), gini(auth)])
t = pd.DataFrame(rows, columns=["", "Gini (videos)", "Top 1% share", "Top 10% share", "Gini (creators)"])
log(t.to_markdown(index=False, floatfmt=".3f") + "\n")
# note: random exposure is the benchmark; its Gini is not 0 because draw counts vary and the sample needs >= 50
log(f"- algorithmic / random Gini across videos: {t.iloc[1, 1] / t.iloc[0, 1]:.1f} times\n")

fig, ax = plt.subplots(figsize=(5, 4.2))
ax.plot([0, 1], [0, 1], color=GRAY, lw=1, ls=(0, (3, 3)))
for vals, c, lab in [(V.n_rand, BLUE, "Random"), (V.E, ORANGE, "Algorithm")]:
    x, y = lorenz(vals)
    ax.plot(x, y, color=c, lw=2, label=f"{lab} (Gini {gini(vals):.2f})")
ax.set(xlabel="Cumulative share of videos (least exposed first)", ylabel="Cumulative share of impressions",
       xlim=(0, 1), ylim=(0, 1), title="Exposure concentration across videos")
ax.title.set_color(INK)
ax.legend(frameon=False, loc="upper left")
fig.savefig(FIG / "fig1_lorenz.png"); plt.close(fig)

# ---------- R2/R3 quality vs exposure, hidden gems ----------
log("## R2. Does exposure follow quality?")
# Spearman = correlation of ranks; robust to the very skewed exposure distribution
rho_q = spearmanr(V.q, V.E).statistic
rho_adj = spearmanr(V.q_adj, V.E).statistic
log(f"- Spearman(quality, algorithmic exposure): shrunk long-view rate {rho_q:.4f}; duration-adjusted percentile {rho_adj:.4f}")
log(f"- Spearman(random long-view rate, algorithm-feed long-view rate), videos with >= 30 algorithmic impressions: "
    f"{spearmanr(V.q[V.n_std >= 30], V.lv_std[V.n_std >= 30]).statistic:.3f} "
    f"(quality measured under random exposure carries over to the real feed)\n")

# 4 x 4 table: quality quartile (rows) x exposure quartile (columns)
V["q_quart"] = pd.qcut(V.q_adj, 4, labels=["Q1 low", "Q2", "Q3", "Q4 high"])
# exposure has many ties (11.6% zeros), so rank first; method="first" breaks ties by row order (video_id)
V["E_quart"] = pd.qcut(V.E.rank(method="first"), 4, labels=["E1 low", "E2", "E3", "E4 high"])
ct = pd.crosstab(V.q_quart, V.E_quart, normalize="index")
log("## R3. Hidden gems")
log("Row = quality quartile, column = exposure quartile, cell = share of row (25% each if exposure ignored quality):\n")
log(ct.to_markdown(floatfmt=".1%") + "\n")
V["gem"] = (V.q_quart == "Q4 high") & (V.E_quart == "E1 low")
V["overexposed"] = (V.q_quart == "Q1 low") & (V.E_quart == "E4 high")
gems, rest = V[V.gem], V[~V.gem & (V.q_quart == "Q4 high")]
log(f"- Hidden gems (top-quartile quality, bottom-quartile exposure): {len(gems):,} videos "
    f"= {len(gems) / (V.q_quart == 'Q4 high').sum():.1%} of high-quality videos; "
    f"they received {gems.E.sum() / V.E.sum():.2%} of algorithmic impressions")
log(f"- Over-exposed (bottom-quartile quality, top-quartile exposure): {int(V.overexposed.sum()):,} videos, "
    f"{V[V.overexposed].E.sum() / V.E.sum():.1%} of algorithmic impressions")
log(f"- Hidden gems vs other high-quality videos: shrunk random long-view rate {gems.q.mean():.3f} vs {rest.q.mean():.3f}; "
    f"prior-period exposure (median) {gems.E_pre.median():.0f} vs {rest.E_pre.median():.0f}")

# Sensitivity of the gem count to tie-breaking at the E1 cut-off (ties broken by video_id order above).
cut = V.loc[V.E_quart == "E1 low", "E"].max()                    # highest exposure value inside E1
q4 = V.q_quart == "Q4 high"
rng_tb = np.random.default_rng(0)
tb = [(q4 & (pd.qcut((V.E + rng_tb.random(len(V)) * 1e-3).rank(method="first"), 4, labels=False) == 0)).sum()
      for _ in range(200)]                                         # 200 random tie-breaks
log(f"- Tie-breaking check: the E1 cut-off falls inside the tie at E = {cut:.0f} "
    f"({int((V.E == cut).sum())} videos, {int(((V.E == cut) & (V.E_quart == 'E1 low')).sum())} of them in E1). "
    f"Gems with 200 random tie-breaks: mean {np.mean(tb):.1f}, range {min(tb)}-{max(tb)}; "
    f"with a value threshold: {int((q4 & (V.E < cut)).sum())} (E < {cut:.0f}) or {int((q4 & (V.E <= cut)).sum())} (E <= {cut:.0f})\n")

fig, ax = plt.subplots(figsize=(5.4, 4.6))
oth = V[~V.gem & ~V.overexposed]
ax.scatter(oth.q_adj, oth.E_pct, s=4, color=GRAY, alpha=0.35, lw=0, label="Other videos")
ax.scatter(V[V.overexposed].q_adj, V[V.overexposed].E_pct, s=6, color=BLUE, alpha=0.7, lw=0,
           label=f"Over-exposed (n={int(V.overexposed.sum())})")
ax.scatter(gems.q_adj, gems.E_pct, s=6, color=ORANGE, alpha=0.8, lw=0, label=f"Hidden gems (n={len(gems)})")
for v_ in (0.25, 0.75):
    ax.axvline(v_, color=GRAY, lw=0.8, ls=(0, (3, 3))); ax.axhline(v_, color=GRAY, lw=0.8, ls=(0, (3, 3)))
ax.set(xlabel="Quality percentile (random exposure, duration-adjusted)",
       ylabel="Algorithmic exposure percentile", xlim=(0, 1), ylim=(0, 1),
       title=f"Quality vs exposure (Spearman ρ = {rho_adj:.2f})")
ax.title.set_color(INK)
ax.legend(frameon=False, loc="upper center", bbox_to_anchor=(0.5, -0.13), ncol=3, fontsize=8, markerscale=3)
fig.savefig(FIG / "fig2_quality_vs_exposure.png"); plt.close(fig)

# binned view: mean exposure by quality decile (error bars = 95% CI of the mean)
V["q_dec"] = pd.qcut(V.q_adj, 10, labels=False) + 1
b = V.groupby("q_dec").E.agg(["mean", "sem", "median"])
fig, ax = plt.subplots(figsize=(5.4, 3.6))
ax.bar(b.index, b["mean"], color=BLUE, width=0.7)
ax.errorbar(b.index, b["mean"], yerr=1.96 * b["sem"], fmt="none", ecolor=INK2, lw=1, capsize=2)
ax.set(xlabel="Quality decile (1 = lowest)", ylabel="Mean algorithmic impressions per video",
       xticks=range(1, 11), title="Exposure rises with quality, mostly in the top deciles")
ax.title.set_color(INK)
fig.savefig(FIG / "fig3_exposure_by_quality_decile.png"); plt.close(fig)

# ---------- R4 path dependence ----------
log("## R4. Path dependence: what predicts current exposure?")
z = lambda s: (s - s.mean()) / s.std()          # standardise: coefficients are in standard deviations
X = pd.DataFrame({"Quality (random, duration-adj.)": z(V.q_adj),
                  "log prior exposure (previous 2 weeks)": z(np.log1p(V.E_pre)),   # log1p = log(1 + x), handles 0
                  "log duration": z(np.log(V.video_duration))})
# one 0/1 column per upload type; the first type is the reference group
X = X.join(pd.get_dummies(V.upload_type.fillna("NA"), prefix="type", drop_first=True, dtype=float))
y = z(np.log1p(V.E)).values
res = []
# model (1) leaves out prior exposure (column 1); model (2) uses all columns
for label, cols in [("(1) quality only", X.columns[:1].tolist() + X.columns[2:].tolist()),
                    ("(2) + prior exposure", X.columns.tolist())]:
    bcoef, se, r2 = ols_hc1(y, X[cols].values)
    d = dict(zip(cols, zip(bcoef, se)))
    res.append({"Model": label, **{k: f"{d[k][0]:.3f} ({d[k][1]:.3f})" if k in d else "" for k in X.columns[:3]},
                "R²": f"{r2:.3f}"})
log("Standardized OLS, outcome = z(log(1 + current algorithmic exposure)); HC1 s.e. in parentheses; "
    "upload-type dummies included.\n")
log(pd.DataFrame(res).to_markdown(index=False) + "\n")
# Interpretation: prior exposure is itself related to quality, so model (2)'s quality coefficient is the
# association of quality with current exposure AMONG videos with the same prior exposure, not "all of quality".
log(f"- Spearman(quality, prior exposure) = {spearmanr(V.q_adj, V.E_pre).statistic:.3f}: prior exposure partly reflects "
    f"quality, so the coefficient in (2) is quality's association beyond prior exposure. Correlational, not causal.\n")

# ---------- R5 creator fairness ----------
log("## R5. Creator fairness of exposure (exposure share vs merit share)")
# merit = sum of duration-adjusted quality over the creator's sample videos; it grows with the number of videos,
# i.e. exposure is compared with "number of videos x their quality"
A["merit"] = A.q_sum
A["ratio"] = (A.E / A.E.sum()) / (A.merit / A.merit.sum())        # 1 = exposure proportional to merit
# creators grouped by prior exposure quintile (ties broken by row order, as above)
A["prior_q"] = pd.qcut(A.E_pre.rank(method="first"), 5, labels=["P1 lowest", "P2", "P3", "P4", "P5 highest"])
g = A.groupby("prior_q", observed=True).agg(creators=("E", "size"), exposure=("E", "sum"), merit=("merit", "sum"))
g["exposure share"] = g.exposure / g.exposure.sum()
g["merit share"] = g.merit / g.merit.sum()
g["exposure / merit"] = g["exposure share"] / g["merit share"]
log("Creators grouped by prior-period exposure quintile; exposure/merit = 1 means exposure proportional to merit "
    "(Singh & Joachims 2018).\n")
log(g[["creators", "exposure share", "merit share", "exposure / merit"]].to_markdown(floatfmt=("", ".0f", ".3f", ".3f", ".3f")) + "\n")
# robustness: same ratio with merit = sum of the shrunk rate q (no duration adjustment)
A["merit_raw"] = V.groupby("author_id").q.sum()
rob = A.groupby("prior_q", observed=True).apply(lambda d: (d.E.sum() / A.E.sum()) / (d.merit_raw.sum() / A.merit_raw.sum()))
log(f"- Robustness, merit = sum of raw shrunk long-view rate: exposure/merit by group = "
    f"{', '.join(f'{x:.2f}' for x in rob)}")
log(f"- {(A.ratio < 0.5).mean():.1%} of creators receive less than half of their merit-proportional exposure; "
    f"{(A.E == 0).mean():.1%} receive none")
log(f"- merit is a sum, so it scales with the number of videos: sample videos per creator mean "
    f"{A.n_videos.mean():.2f}, max {A.n_videos.max()}; {(A.n_videos == 1).mean():.1%} of creators have one video. "
    f"Grouping by prior exposure partly restates R4.\n")

fig, ax = plt.subplots(figsize=(5.4, 3.6))
ax.bar(range(5), g["exposure / merit"], color=BLUE, width=0.6)
ax.axhline(1, color=INK2, lw=1, ls=(0, (3, 3)))
ax.text(-0.4, 1.05, "proportional to merit", ha="left", va="bottom", color=INK2, fontsize=8)
for k, val in enumerate(g["exposure / merit"]):
    ax.text(k, val + 0.05, f"{val:.2f}", ha="center", va="bottom", color=INK, fontsize=8)
ax.set(xticks=range(5), xticklabels=g.index, xlabel="Creator group by prior-period exposure",
       ylabel="Exposure share ÷ merit share", title="Exposure goes to creators who already had it")
ax.title.set_color(INK)
fig.savefig(FIG / "fig4_creator_exposure_merit.png"); plt.close(fig)

(ROOT / "reports/03_prelim_results.md").write_text("\n".join(out) + "\n")
V.to_parquet(P / "video_level.parquet")
